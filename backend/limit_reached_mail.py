"""Письма тем, у кого закончились бесплатные минуты. Три варианта + замер.

Кому. Человек прошёл тест, оставил почту и разговаривал с Фреди, пока не
упёрся в лимит. Самый тёплый адрес из всех, что у нас есть: он знает,
зачем сюда ходят, и оборвался не потому, что стало неинтересно, а потому
что кончилось время.

Зачем. С 15.09.2026 разговоры удлинились — медиана выросла с одной
реплики до четырёх, — и в стену теперь упирается больше людей, чем пишет
первое сообщение: 22 показа против 15 сообщений за 17.09. Стена при этом
почти тупик: за неделю 114 показов дали 9 кликов «подписаться» и одну
оплату. Письмо — единственный способ позвать обратно того, кто ушёл на
полуслове.

ПОЧЕМУ ТРИ ВАРИАНТА, А НЕ ОДИН. Владелец просил замерить, после какого
письма возвращаются. Угадывать тут нечего: мы ни разу не писали этим
людям и не знаем, что их трогает — напоминание о незаконченном разговоре,
готовность быть рядом без повода или практическая польза. Варианты
различаются ровно этим и ничем больше: у всех одна тема ссылки, одна
кнопка, один блок про ярлык. Разное — только то, ЧЕМ зовут.

  A «продолжим» — упор на оборванный разговор. Гипотеза: работает
    незакрытость, человек помнит, на чём остановился.
  B «я на месте» — упор на постоянство. Гипотеза: работает не повод, а
    то, что есть куда прийти без повода.
  C «под рукой» — упор на ярлык и удобство. Гипотеза: человек не
    возвращается не потому, что не хочет, а потому что не помнит адрес.

Вариант закрепляется за адресом намертво (хеш почты): при повторной
рассылке человек получит то же письмо, а не разные, — иначе замер
превратится в кашу.

ЧЕГО В ПИСЬМАХ НЕТ НАМЕРЕННО:
• продажи подписки. Человека оборвали на середине; просить у него денег
  в ту же минуту — худший момент из возможных. Письма зовут вернуться,
  а не платить. Если вернётся и разговорится — стену он увидит сам;
• обещаний «всё будет хорошо» и прочей терапевтической ваты;
• упрёка «вы не дописали». Лимит называется один раз и без нажима:
  минуты вернулись, дальше про дело.

Ярлык на экране — просьба владельца 17.09.2026. Человек, у которого Фреди
лежит на домашнем экране, возвращается сам; человек, которому надо
вспомнить адрес и набрать его в поиске, не возвращается никогда. Шаги
описаны словами, а не цитатами пунктов меню: Chrome переименовывает их от
версии к версии, и точная цитата устареет быстрее, чем письмо дойдёт.

Отправкой модуль не занимается — только собирает текст и назначает
вариант. Кому и когда слать, решает ручка в main.py, и запускает её
владелец.
"""

from __future__ import annotations

import hashlib
from html import escape
from typing import Dict, List, Optional, Tuple

SITE = "https://meysternlp.ru"
FREDI_URL = SITE + "/fredi/"

VARIANTS: Tuple[str, ...] = ("a", "b", "c")

# Колонка под вариант. Сама таблица и followed_up_at заведены ещё в
# short_test_mail.py — там их создавали заранее под эту рассылку, но
# рассылку так и не построили: за всё время ни одной записи.
ADD_VARIANT_COLUMN_SQL = (
    "ALTER TABLE fredi_test_leads "
    "ADD COLUMN IF NOT EXISTS followup_variant TEXT"
)

# Кого зовём: оставил почту, письмо ещё не уходило, не отписался.
# Возраст лида — параметр ручки: слать в тот же час, когда человек ушёл,
# рано, а через неделю поздно.
SELECT_RECIPIENTS_SQL = """
SELECT id, email, test, band, opt_out_token
FROM fredi_test_leads
WHERE followed_up_at IS NULL
  AND opted_out_at IS NULL
  AND email <> ''
  AND created_at < NOW() - ($1 || ' hours')::interval
  AND created_at > NOW() - ($2 || ' days')::interval
ORDER BY created_at
LIMIT $3
"""

MARK_SENT_SQL = (
    "UPDATE fredi_test_leads "
    "SET followed_up_at = NOW(), followup_variant = $2 "
    "WHERE id = $1"
)


def variant_for(email: str) -> str:
    """Вариант, закреплённый за адресом навсегда.

    Не random и не счётчик: и то и другое при повторном запуске рассылки
    дало бы одному человеку разные письма, а замер — бессмыслицу.
    """
    h = hashlib.sha256((email or "").strip().lower().encode("utf-8")).hexdigest()
    return VARIANTS[int(h[:8], 16) % len(VARIANTS)]


def link_for(variant: str) -> str:
    """Ссылка с меткой варианта — по ней и считаем возвраты."""
    return f"{FREDI_URL}?from=mail_limit&v={variant}"


# Шаги для ярлыка. Три строки: четвёртая платформа читателю не нужна, а
# список длиннее трёх в письме не дочитывают.
_SHORTCUT_STEPS = [
    ("Айфон", "в Safari нажмите «Поделиться» внизу экрана и выберите "
              "«На экран „Домой“»."),
    ("Андроид", "в Chrome откройте меню из трёх точек справа вверху и "
                "выберите «Добавить на главный экран»."),
    ("Компьютер", "в Chrome откройте меню из трёх точек и найдите пункт "
                  "со словом «Ярлык» — он создаст значок на рабочем столе."),
]

# Тело каждого варианта: тема, первый абзац, второй абзац, подпись кнопки.
# Блок про ярлык общий и добавляется ниже — он в письме не ради варианта,
# а ради возврата вообще.
_BODIES: Dict[str, Dict[str, str]] = {
    "a": {
        "subject": "Минуты вернулись — можно продолжить",
        "p1": "В прошлый раз наш разговор оборвался на середине: "
              "закончились бесплатные минуты. Они уже вернулись.",
        "p2": "Если та мысль всё ещё с вами — продолжим с того места, "
              "где остановились.",
        "cta": "Продолжить разговор",
    },
    "b": {
        "subject": "Я на месте",
        "p1": "Мы не договорили в прошлый раз — у нас кончилось время. "
              "Оно вернулось, но письмо не поэтому.",
        "p2": "Я здесь каждый день, и приходить с поводом необязательно. "
              "Иногда полезнее прийти, когда ничего не случилось.",
        "cta": "Написать Фреди",
    },
    "c": {
        "subject": "Чтобы меня не искать",
        "p1": "В прошлый раз время закончилось на середине разговора — "
              "оно уже вернулось.",
        "p2": "Но главное не это. Меня неудобно искать: каждый раз надо "
              "вспоминать адрес. Это чинится за полминуты — ниже показываю как.",
        "cta": "Открыть Фреди",
    },
}


def _greeting(name: Optional[str]) -> str:
    """Имя, если знаем. «Здравствуйте, друг» звучит как рассылка."""
    n = (name or "").strip()
    return f"Здравствуйте, {n}!" if n else "Здравствуйте!"


def _test_line(test_title: Optional[str]) -> str:
    """Отсылка к тесту — только если он правда был.

    Без неё письмо читается как массовая рассылка; с выдуманным названием
    теста — как чужая рассылка, что хуже вдвое.
    """
    t = (test_title or "").strip()
    if not t:
        return "Я помню, о чём мы говорили, — объяснять заново не придётся."
    return (f"Ваш разбор по тесту «{t}» у меня перед глазами, и прошлый "
            f"разговор тоже — объяснять заново не придётся.")


def build_email(
    email: str,
    name: Optional[str] = None,
    test_title: Optional[str] = None,
    optout_link: Optional[str] = None,
    variant: Optional[str] = None,
) -> Tuple[str, str, str, str]:
    """Возвращает (вариант, тема, текст, html).

    Вариант можно передать явно — это нужно ручке, чтобы записать в базу
    ровно то, что отправила, а не пересчитывать хеш второй раз.
    """
    v = (variant or variant_for(email)).lower()
    if v not in _BODIES:
        v = variant_for(email)
    b = _BODIES[v]
    hello = _greeting(name)
    remember = _test_line(test_title)
    link = link_for(v)

    steps_text = "\n".join(f"— {where}: {how}" for where, how in _SHORTCUT_STEPS)
    steps_html = "".join(
        f'<li style="margin-bottom:7px"><b>{escape(where)}</b> — {escape(how)}</li>'
        for where, how in _SHORTCUT_STEPS
    )

    text = (
        f"{hello}\n\n"
        f"{b['p1']}\n\n"
        f"{remember}\n\n"
        f"{b['p2']}\n\n"
        f"{b['cta']}: {link}\n\n"
        "Чтобы не искать меня заново через поиск, положите значок на экран — "
        "открываюсь одним касанием, как обычное приложение:\n"
        f"{steps_text}\n\n"
        "— Фреди, виртуальный психолог\n"
    )

    html = (
        '<!doctype html><html><body style="font-family:-apple-system,Segoe UI,Roboto,'
        'sans-serif;max-width:560px;margin:24px auto;padding:0 16px;color:#1c1c1e;'
        'line-height:1.55">'
        f"<p>{escape(hello)}</p>"
        f"<p>{escape(b['p1'])}</p>"
        f"<p>{escape(remember)}</p>"
        f"<p>{escape(b['p2'])}</p>"
        f'<p style="margin:24px 0"><a href="{link}" '
        'style="display:inline-block;background:#3b82ff;color:#fff;text-decoration:none;'
        'padding:13px 24px;border-radius:26px;font-weight:700;font-size:15px">'
        f"{escape(b['cta'])}</a></p>"
        '<p style="margin:26px 0 8px"><b>Чтобы меня не искать</b></p>'
        "<p>Положите значок на экран — открываюсь одним касанием, как обычное "
        "приложение:</p>"
        f'<ul style="padding-left:20px;margin:10px 0 0">{steps_html}</ul>'
        '<p style="margin-top:26px">— Фреди, виртуальный психолог</p>'
        + (f'<hr style="margin-top:36px;border:none;border-top:1px solid #e5e5ea">'
           f'<p style="font-size:12px;color:#8e8e93">Если письма от нас больше не нужны — '
           f'<a href="{optout_link}" style="color:#8e8e93">отписаться в один клик</a>.</p>'
           if optout_link else "")
        + "</body></html>"
    )
    return v, b["subject"], text, html


def all_previews(test_title: Optional[str] = "Тревога") -> List[Dict[str, str]]:
    """Три письма подряд — для предпросмотра владельцем до рассылки."""
    out = []
    for v in VARIANTS:
        _, subject, text, _ = build_email(
            email=f"preview-{v}@example.com", test_title=test_title, variant=v)
        out.append({"variant": v, "subject": subject, "text": text})
    return out
