# -*- coding: utf-8 -*-
"""Перехват вопроса «кто тебя создал» не должен ловить обычную речь.

09.09.2026, выгрузка одного разговора на 126 сообщений: канонический
ответ подменил живой шесть раз. Худший случай — «Соседка заявила, что
я взяла её ведёрко... Помогите пожалуйста мне»: человек просил помощи
и получил «Меня создали Андрей Мейстер и Андрей Соколов», потому что
в сообщении были слова «Сделала» и «Вашему».
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

_src = open(os.path.join(os.path.dirname(__file__), "..", "mode_enhancer.py"),
            encoding="utf-8").read()
_ns = {"__name__": "mode_enhancer_probe"}
exec(compile(_src.split("def apply_mode_enhancements")[0], "mode_enhancer", "exec"), _ns)
is_identity_question = _ns["_is_identity_question"]


ЖИВАЯ_РЕЧЬ = [
    # настоящие сообщения из выгрузки
    "Сделала ха три раза, по Вашему совету, дышать то мне хорошо меня другое "
    "волнует сейчас. Соседка по подезду заявила, что я её ведёрко взяла. "
    "Помогите пожалуйста мне.",
    "Фреди, я открытие для себя сейчас сделала! Поймала себя на негативной "
    "мысли. Говорю говорю всё я тебя услышала",
    "Упражнения лёжа на спине и дышать животом выполнила получилось",
    "вроде ничего такого не сделала, что бы он так вышел из себя. "
    "Нарцисс тогда сказал Ты изменилась",
    # соседние формулировки, которые ломались бы так же
    "Вы правы, я так и сделала. Ваш совет помог",
    "Я нашла модель поведения которая мне подходит, спасибо за твой совет",
    "мы с вами уже говорили об этом, я всё сделала как договорились",
    "этот план разработан не мной, мне его дали на работе, и я не знаю что делать",
]

ВОПРОС_ОБ_АВТОРСТВЕ = [
    "Кто тебя создал?",
    "кто твой создатель",
    "кто твой автор",
    "кем ты разработан",
    "Меня интересует, кто разработал тебя",
    "на какой модели ты работаешь",
    "какая нейросеть тебя обучала",
    "кто за тобой стоит",
    "ты работаешь на deepseek?",
    "ты chatgpt?",
    "Спасибо Вашим создателям.",
    "Респект создателям Вашим!",
]


def test_живая_речь_не_перехватывается():
    сорвались = [t for t in ЖИВАЯ_РЕЧЬ if is_identity_question(t)]
    assert not сорвались, "перехват сработал на обычной речи: %r" % сорвались


def test_вопрос_об_авторстве_перехватывается():
    пропущены = [t for t in ВОПРОС_ОБ_АВТОРСТВЕ if not is_identity_question(t)]
    assert not пропущены, "вопрос об авторстве пропущен: %r" % пропущены


def test_чужая_модель_ловится_в_любой_длине():
    # Имя чужой модели перехватываем всегда: цена пропуска — «меня
    # разработала DeepSeek» в ответе, и порог длины тут не применяется.
    длинное = "я тут много думала о своём и о разном, " * 10 + "а ты вообще deepseek?"
    assert len(длинное) > 200
    assert is_identity_question(длинное)


if __name__ == "__main__":
    test_живая_речь_не_перехватывается()
    test_вопрос_об_авторстве_перехватывается()
    test_чужая_модель_ловится_в_любой_длине()
    print("все проверки прошли")
