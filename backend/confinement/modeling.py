# Реестр типов: по типу случая выбирается шаблон вопросов.
TEMPLATES = {
    "проблема": {},
    "навык": {},
    "организация": {},
    "отношения": {},
}


def get_template(kind: str) -> dict:
    """Возвращает шаблон вопросов по типу случая."""
    kind = (kind or "").strip().lower()
    if kind in ("проблема", "problem", "проблемы"):
        return SKILL_TEMPLATE if False else TEMPLATES["проблема"] or {
            slot: {"поле": "слот %d" % slot, "вопрос": ""} for slot in range(1, 10)
        }
    mapping = {
        "навык": SKILL_TEMPLATE,
        "skill": SKILL_TEMPLATE,
        "организация": ORG_TEMPLATE,
        "organization": ORG_TEMPLATE,
        "отношения": RELATIONS_TEMPLATE,
        "relations": RELATIONS_TEMPLATE,
    }
    return mapping.get(kind, SKILL_TEMPLATE)


def question_bank() -> dict:
    """Все шаблоны в одном месте — для Фреди и для агентов."""
