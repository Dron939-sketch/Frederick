def step_guide(slot: int) -> dict:
    """Что спрашивать и где искать ответ на конкретном слоте."""
    if slot not in QUESTIONS:
        raise ValueError("слот должен быть от 1 до 9")
    return {
        "слот": slot,
        "вопросы": QUESTIONS[slot],
        "где искать": DATA_SOURCES[slot],
        "что отвергать": REJECTS[slot],
    }


def route() -> list:
    """Полный маршрут заполнения с вопросами по каждому шагу."""
    return [{"номер": slot, "элемент": name, "задача": task,
             "вопросы": QUESTIONS[slot], "где искать": DATA_SOURCES[slot]}
            for slot, name, task in FILL_ORDER]


