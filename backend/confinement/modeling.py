def compare_fillings(проблемная: dict, успешная: dict) -> dict:
    """Сравнивает две карты по элементам: где различие, там направление коррекции."""
    slots = sorted(set(проблемная) | set(успешная))
    differences, same = [], []
    for slot in slots:
        old = str(проблемная.get(slot, "")).strip()
        new = str(успешная.get(slot, "")).strip()
        if old == new:
            same.append(slot)
        else:
            differences.append({"слот": slot, "было": old, "стало": new})
    return {
        "различий": len(differences),
        "совпадает": len(same),
        "различия": differences,
        "совпадающие": same,
        "правило": "элементы и связи, обнаруживающие различия, — направление коррекции",
    }

