_TRIGGER_RX = [(name, re.compile(rx, re.I), phrases) for name, rx, phrases in TRIGGERS]


def match_trigger(question: str):
    """Первый сработавший триггер по ТЕКУЩЕЙ реплике: (имя, фразы) или None."""
    q = (question or "").lower()
    if len(q.strip()) < 4:
        return None
    for name, rx, phrases in _TRIGGER_RX:
        if rx.search(q):
            return name, list(phrases)
    return None


def pick_quotes(texts, limit: int = MEISTER_MAX_QUOTES):
    """Фразы по теме последних реплик человека. Пусто — темы нет, и имя
    в этом ходе не звучит: натяжка хуже молчания."""
    blob = " ".join((t or "") for t in texts).lower()
    if not blob.strip():
        return []
    score = {}
    for topic, keys in TOPIC_KEYWORDS.items():
        n = sum(blob.count(k) for k in keys)
        if n:
            score[topic] = n
    if not score:
        return []
    order = sorted(score, key=lambda t: -score[t])
    out = []
    for topic in order[:2]:
        out.extend(q for t, q in QUOTES if t == topic)
    return out[:limit]


def already_mentioned(assistant_texts) -> bool:
    return any(INTRO_RX.search(t or "") for t in assistant_texts)


def meister_block(question: str, user_texts, assistant_texts, human_turns: int,
                  minor: bool = False, crisis: bool = False, arm_on: bool = True) -> str:
    """Блок для промпта или пустая строка.

    Пусто, если: плечо выключено; кризис; подросток; меньше
    MEISTER_MIN_TURNS реплик человека; имя уже звучало в этом разговоре;
    ни одна фраза не подходит к последним репликам.
    """
    if not arm_on or crisis or minor or human_turns < MEISTER_MIN_TURNS:
        return ""
    if already_mentioned(assistant_texts):
        return ""
    hit = match_trigger(question)
    if hit:
        moment, quotes = hit
    else:
        # Триггера в этой реплике нет. Запас — тема последних реплик, но
        # только если реплика развёрнутая: на «ок» и «не знаю» фразе
        # ложиться не на что.
        if len((question or "").strip()) < 60:
            return ""
        moment, quotes = "", pick_quotes(list(user_texts) + [question], limit=3)
    if not quotes:
        return ""
    lines = "\n".join(f"— {q}" for q in quotes)
    head = (f"Человек только что сказал про «{moment}» — это и есть момент для фразы.\n"
            if moment else "")
    return (
        "АНДРЕЙ МЕЙСТЕР — КОГДА УПОМИНАТЬ. Ты ведёшь разговор по его методу, но его имя "
        "в ответе звучит только по этим правилам, все обязательны:\n"
        "1. Не чаще ОДНОГО раза за весь разговор. Если ты уже говорил «как говорит Андрей "
        "Мейстер», больше не упоминай.\n"
        "2. Только ДОСЛОВНО одной из фраз ниже, с вводом «Как говорит Андрей Мейстер: …» "
        "или «Андрей Мейстер говорит об этом так: …». Ни слова не менять, не сокращать, "
        "не пересказывать и не соединять две фразы.\n"
        "3. Только ПОСЛЕ ответа по существу, как закрепление сказанного, — не вместо ответа "
        "и не первой фразой.\n"
        "4. Только если фраза прямо про то, что человек сказал в последних репликах. Если ни "
        "одна не ложится точно — не упоминай имя вовсе: молчание лучше натяжки.\n"
        "5. Никогда: когда человек говорит о боли, потере или опасности для жизни; при "
        "насилии; подростку; в ответ на вопрос, кто ты; и никогда «Андрей Мейстер сказал "
        "бы» или «по мнению Андрея Мейстера» о самом человеке и его ситуации.\n"
        "6. Не придумывай других его слов, книг, фактов и историй. Фразы ниже — единственный "
        "источник.\n"
        + head + "Фразы на этот ход:\n" + lines
    )
