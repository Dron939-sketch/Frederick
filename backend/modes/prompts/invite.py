# -*- coding: utf-8 -*-
"""Приглашение второго человека в разговор — как в семейной терапии.

04.10.2026, решение владельца: «на разговор с психологом могут
рекомендовать, как в случае с семейной терапией, когда нужны все члены
семьи». Семейный терапевт не просит «порекомендуйте меня» — он говорит
«на следующую встречу приходите с мужем». Это рекомендация, которую
человек выполняет сам, потому что она про его проблему.

Как устроено. Когда разговор идёт про конкретного близкого (партнёр,
ребёнок, родитель) и человек описывает конфликт с одной стороны, Фреди
не раньше шестой реплики человека может один раз предложить: пусть тот
тоже поговорит с Фреди — отдельно и анонимно. Если человек соглашается,
модель ставит в конце ответа служебную метку [[INVITE:кто]]. Приложение
метку снимает, создаёт ссылку через /api/invite/create и показывает
карточку «ссылка для него» с кнопкой «Отправить».

Второй человек приходит по /fredi/?invite=<token>: у него свой разговор,
свои двадцать минут, и ни одно слово первого ему не передаётся — это
условие доверия, без которого никто не пришлёт ссылку мужу.

Блок подсказки не ставится, если ссылка уже выдана (invite_sent) — иначе
модель предлагала бы её каждый ход, как делала с курсами до #719.
"""
import re

INVITE_MIN_TURNS = 6

# Метка в ответе модели. До 20 символов внутри: «партнёр», «муж», «мама»,
# «сын» — как назовёт модель. Служебная, человеку не показывается.
INVITE_MARK_RX = re.compile(r"\s*\[\[\s*INVITE\s*:\s*([^\]\n]{1,20}?)\s*\]\]\s*", re.I)


def strip_mark(text: str) -> str:
    """Текст ответа без метки — для истории и для чтения вслух."""
    if not text:
        return text
    return INVITE_MARK_RX.sub(" ", text).strip()


def find_mark(text: str):
    """Кого приглашают, если метка есть; иначе None."""
    if not text:
        return None
    m = INVITE_MARK_RX.search(text)
    return m.group(1).strip() if m else None


def offer_block(human_turns: int, invite_sent: bool, invited_as: str = "") -> str:
    """Подсказка модели, когда и как предложить приглашение.

    Пустая строка — не предлагать: рано (меньше INVITE_MIN_TURNS своих
    реплик), ссылка уже выдана, или человек сам пришёл по приглашению
    (цепочки приглашений не нужны).
    """
    if invited_as or invite_sent or human_turns < INVITE_MIN_TURNS:
        return ""
    return (
        "ПРИГЛАШЕНИЕ ВТОРОГО ЧЕЛОВЕКА. Если разговор идёт про конкретного близкого "
        "(партнёр, муж, жена, сын, дочь, мама, папа) и человек описывает конфликт с ним "
        "со своей стороны, ты можешь ОДИН раз за разговор предложить, чтобы тот человек "
        "тоже поговорил с тобой — отдельно и анонимно. Скажи это своими словами, но с "
        "тремя обязательными мыслями: ты слышишь только одну половину; второй разговор "
        "будет отдельным — он не увидит этих слов, а этот человек не увидит его слов; "
        "после этого ты сможешь сказать больше. Закончи вопросом вроде «хотите, дам "
        "ссылку для него?». Предлагай только если это уместно по ходу разговора, не "
        "вместо ответа по существу и не в первой же фразе про близкого.\n"
        "Если человек соглашается (да, давайте, хочу, пришлите) — ответь коротко, что "
        "ссылка появится под этим сообщением, и в самом конце ответа поставь служебную "
        "метку [[INVITE:кто]], где вместо «кто» — одно слово: партнёр, муж, жена, сын, "
        "дочь, мама, папа или другой. Метку не объясняй и не упоминай. Без согласия "
        "метку не ставь.\n"
        "НЕ предлагай: в кризисном разговоре; подростку; если человек описывает насилие, "
        "угрозы или контроль со стороны этого близкого; если он прямо сказал, что не "
        "хочет вовлекать второго."
    )


def invitee_block(invited_as: str) -> str:
    """Подсказка модели для того, кто пришёл по приглашению."""
    who = (invited_as or "близкий человек").strip()
    return (
        f"ЧЕЛОВЕК ПРИШЁЛ ПО ПРИГЛАШЕНИЮ. Его пригласил близкий ({who}), который уже "
        "говорил с тобой о своей стороне ситуации. Ты НЕ знаешь слов того разговора и не "
        "можешь их передать — у тебя их нет. Если спросит, что сказал другой, честно "
        "ответь: ты не передаёшь ничьи слова, этот разговор только его. Веди обычный "
        "разговор: расспроси, как он сам видит, что происходит. Не вставай ни на чью "
        "сторону и не пересказывай позицию пригласившего. Не торопи с выводами."
    )
