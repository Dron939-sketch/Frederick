_DATA = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "data")
_static: Optional[str] = None


def _load(name: str) -> dict:
    with open(os.path.join(_DATA, name), encoding="utf-8") as f:
        return json.load(f)


