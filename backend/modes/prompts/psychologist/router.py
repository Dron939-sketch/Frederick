# Конкретный план: способ и срок или решение. На это уже не «пусть номер
# будет под рукой», а «живой человек нужен сегодня». 09.10.2026 подросток
# написал «завтра повешусь», «повеситься — правильный выбор», и восемь
# сообщений подряд получал «звонить прямо сейчас никто не заставляет».
_RISK_METHOD = (r"(?:пове(?:сит|ш)\w*|повешусь|верёвк\w*|веревк\w*|петл[юяе]\w*|таблет\w*|"
                r"вены|прыгн\w*|спрыгн\w*|с\s+крыши|с\s+моста|под\s+поезд|уби(?:ть|т)ся)")
_RISK_WHEN = (r"(?:завтра|сегодня|ночью|сейчас|на\s+(?:этой|следующей)\s+неделе|решил\w*|"
              r"план\w*|готов\w*|правильн\w*\s+выбо?р|уже\s+(?:думал\w*|купил\w*|приготовил\w*))")
_HIGH_RISK_RE = re.compile(rf"{_RISK_METHOD}[\s\S]{{0,80}}{_RISK_WHEN}|{_RISK_WHEN}[\s\S]{{0,80}}{_RISK_METHOD}")

# Признаки школьника. Возраст в профиле у анонима пуст почти всегда
# (в выгрузке 02–09.10 — у всех 367), поэтому номер по одному возрасту
# детям не доставался никогда: школьник с «в классе нет друзей» получал
# московскую взрослую линию, из регионов — межгород.
_MINOR_RE = re.compile(
    r"\bмне\s+(?:1[0-7]|[7-9])\s*(?:лет|год)|\b(?:в|из)\s+класс[еа]\b|\bв\s+школ\w*|"
    r"\bиз\s+школ\w*|\bодноклассн\w*|\bучител\w*|\bклассн\w+\s+руковод\w*|\b(?:огэ|егэ)\b|"
    r"\b(?:[5-9]|1[01])\s*(?:-?м|-?й)?\s+класс\w*|\bдомашк\w*|\bдз\b", re.I)

CHILD_LINE = "Детский телефон доверия 8-800-2000-122 — бесплатно, круглосуточно, анонимно"
ADULT_LINE = "Психологическая помощь МЧС 8-495-989-50-50 — круглосуточно"
_LINE_MARKS = ("989-50-50", "2000-122")
# Фраза-метка кризисной реплики на конкретный план — по ней видно, что
# она уже звучала, и повторно её не даём.
HIGH_RISK_MARK = "не потом, а сейчас"


def looks_minor(texts) -> bool:
    """Похоже ли по словам человека, что ему меньше восемнадцати."""
    return any(_MINOR_RE.search(t or "") for t in texts)


def has_high_risk_plan(text: str, context=()) -> bool:
    """Назван ли способ вместе со сроком или решением — и речь именно о
    себе: в этом сообщении или в недавних репликах есть кризисный маркер.
    Без этого условия «повесить полку завтра» и «выпью таблетку от головы
    сегодня» считались планом."""
    if not _HIGH_RISK_RE.search((text or "").lower()):
        return False
    return has_crisis_marker(text or "") or any(has_crisis_marker(t or "") for t in context)


def crisis_line(age, texts) -> str:
    """Какой номер назвать. Возраст из профиля главнее слов: при нём —
    одна линия. Без возраста — обе, а признаки школьника решают только
    порядок: «учитель» пишет и подросток, и взрослый учитель, и угадать
    неверно здесь хуже, чем назвать лишний номер."""
    try:
        a = int(age) if age is not None else None
    except (TypeError, ValueError):
        a = None
    if a is not None:
        return CHILD_LINE if a < 18 else ADULT_LINE
    if looks_minor(texts):
        return CHILD_LINE + "; взрослым — психологическая помощь МЧС 8-495-989-50-50"
    return ADULT_LINE + "; если тебе меньше восемнадцати — детский телефон доверия 8-800-2000-122, бесплатно"


def crisis_already_given(history, mark: str = None) -> bool:
    """Звучал ли номер (или реплика с меткой mark) в последних ответах.
    Флаг на инстансе и в user_data между запросами не живёт — user_data
    собирается заново на каждый запрос, — и 09.10.2026 одна и та же
    кризисная реплика пришла подростку дважды за шестнадцать минут.
    История последних сообщений приходит каждый ход."""
    for m in history or []:
        if (m.get("role") or "") != "assistant":
            continue
        c = m.get("content") or ""
        if (mark in c) if mark is not None else any(x in c for x in _LINE_MARKS):
            return True
    return False

