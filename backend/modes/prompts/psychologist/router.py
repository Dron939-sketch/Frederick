# Фильтр жил только в BasicMode и PsychologistMode. Но человек в кризисе
# пишет туда, где оказался: 03.09.2026 в разборе обращений нашлась
# шестнадцатилетняя, писавшая Коучу. Режим не должен решать, прозвучит
# телефон доверия или нет, поэтому текст и правило вынесены сюда — их
# используют Коуч и Тренер, у которых своего кризисного ответа не было.
# Номер подставляется по crisis_line: до 09.10.2026 здесь всем стояла
# детская линия, и взрослый клиент Коуча получал чужой телефон.
CRISIS_NOTICE = (
    "Остановлюсь. То, что вы сейчас написали, важнее задачи, ради которой мы "
    "здесь. Я никуда не денусь и мы продолжим — но сначала одно.\n\n"
    "Когда появляются мысли не жить или причинить себе вред, рядом должен "
    "быть живой человек. {line}. Если совсем остро — 112.\n\n"
    "Скажите, эти мысли появились сегодня или уже какое-то время с вами?"
)


def crisis_reply(mode, question: str):
    """Вернуть кризисный текст, если он нужен, иначе None.

    Номер даётся один раз за сессию: повторять его на каждое сообщение —
    значит превратить поддержку в шаблонную отписку. Флаг хранится и на
    инстансе, и в user_data, потому что инстанс режима создаётся заново
    на каждый HTTP-запрос."""
    try:
        if not has_crisis_marker(question):
            return None
        hist = getattr(mode, "history", None) or []
        shown = (
            getattr(mode, "_crisis_said", False)
            or bool(getattr(mode, "user_data", {}).get("crisis_notice_shown"))
            or crisis_already_given(hist)
        )
        if shown:
            return None
        mode._crisis_said = True
        try:
            mode.user_data["crisis_notice_shown"] = True
        except Exception:
            pass
        texts = [question] + [m.get("content") or "" for m in hist if m.get("role") == "user"]
        line = crisis_line(getattr(mode, "age", None), texts).replace("если тебе", "если вам")
        return CRISIS_NOTICE.format(line=line)
    except Exception:
        return None


def quick_classify(user_message: str) -> Optional[str]:
    """
    Быстрая классификация по регуляркам.
    
    Returns:
        Код метода или None, если неоднозначно
    """
    text = user_message.lower()
    scores: Dict[str, int] = {}
    
    for category, patterns in QUICK_RULES.items():
        hits = sum(1 for p in patterns if re.search(p, text))
        if hits > 0:
            scores[category] = hits
    
    if not scores:
        return None
    
    # Сортируем по убыванию
    sorted_scores = sorted(scores.items(), key=lambda x: -x[1])
    
    # Если явный лидер (разница с остальными >= 2) — вернуть
    if len(sorted_scores) == 1 or sorted_scores[0][1] - sorted_scores[1][1] >= 2:
        return sorted_scores[0][0]
    
    return None  # Неоднозначно — в LLM


async def llm_classify(
    user_message: str,
    deepseek_client,
    timeout: float = 3.0
) -> Dict[str, Any]:
    """
    Классификация через LLM.
    
    Args:
        user_message: Сообщение пользователя
        deepseek_client: Клиент для вызова DeepSeek
        timeout: Таймаут в секундах
    
    Returns:
        Словарь с category, confidence, reason
    """
    try:
        import asyncio
        
        # Вызов с таймаутом
        async def _call():
            return await deepseek_client._call_deepseek(
                system_prompt=LLM_CLASSIFIER_SYSTEM_PROMPT,
                user_prompt=user_message,
                max_tokens=150,
                temperature=0.2,
            )

        response = await asyncio.wait_for(_call(), timeout=timeout)
        if not response:
            raise ValueError("empty response")
        text = response.strip()
        
        # Очистка от markdown-обёртки
        text = re.sub(r"^```(?:json)?\s*", "", text)
        text = re.sub(r"\s*```$", "", text)
        
        result = json.loads(text)
        
        # Валидация
        valid_categories = {
            "cbt", "logo", "existential", "analytical",
            "psychoanalysis", "gestalt", "transactional", "person_centered"
        }
        
        category = result.get("category", "person_centered")
        if category not in valid_categories:
            category = "person_centered"
        
        confidence = float(result.get("confidence", 0.5))
        confidence = max(0.0, min(1.0, confidence))  # Ограничиваем
        
        return {
            "category": category,
            "confidence": confidence,
            "reason": result.get("reason", "классификация через LLM"),
        }
        
    except asyncio.TimeoutError:
        return {
            "category": "person_centered",
            "confidence": 0.3,
            "reason": "таймаут классификатора",
        }
    except (json.JSONDecodeError, ValueError, KeyError, TypeError) as e:
        return {
            "category": "person_centered",
            "confidence": 0.3,
            "reason": f"ошибка классификатора: {type(e).__name__}",
        }


async def classify(
    user_message: str,
    history: List[Dict[str, str]] = None,
    exclude_methods: List[str] = None,
    deepseek_client = None,
    confidence_threshold: float = 0.45,
) -> Dict[str, Any]:
    """
    Основная функция Router. Гибридная классификация.
    
    Args:
        user_message: Текущее сообщение пользователя
        history: История диалога (опционально, пока не используется)
        exclude_methods: Список методов для исключения
        deepseek_client: Клиент DeepSeek (обязателен для LLM-классификации)
        confidence_threshold: Порог уверенности для LLM
    
    Returns:
        Словарь с method_code, confidence, reason, source
    """
    exclude_methods = exclude_methods or []
    
    # Шаг 1: быстрая классификация по регуляркам
    quick = quick_classify(user_message)
    if quick and quick not in exclude_methods:
        return {
            "method_code": quick,
            "confidence": 0.9,
            "reason": "точное совпадение по ключевым маркерам",
            "source": "regex",
        }
    
    # Шаг 2: LLM-классификация (если есть клиент)
    if deepseek_client:
        llm_result = await llm_classify(user_message, deepseek_client)
        
        # Шаг 3: проверка порога и исключений
        if (llm_result["confidence"] >= confidence_threshold
                and llm_result["category"] not in exclude_methods):
            return {
                "method_code": llm_result["category"],
                "confidence": llm_result["confidence"],
                "reason": llm_result["reason"],
                "source": "llm",
            }
    
    # Шаг 4: fallback. Раньше был Роджерс — но это создавало проблему
    # «бесконечного отражения без действия» на любой неопределённый запрос.
    # Теперь по умолчанию CBT (Beck) — у него встроена структура, action plan
    # и психообразование, что для большинства случаев продуктивнее.
    if "cbt" not in exclude_methods:
        return {
            "method_code": "cbt",
            "confidence": 0.4,
            "reason": "fallback: action-oriented подход для общего запроса",
            "source": "fallback",
        }
    # Если CBT тоже исключён — Роджерс как последний резерв.
    return {
        "method_code": "person_centered",
        "confidence": 0.4,
        "reason": "fallback: CBT исключён, остался person_centered",
        "source": "fallback",
    }
