def _level_key(level) -> str:
    try:
        n = int(level)
    except Exception:
        return "mid"
    if n <= 3:
        return "low"
    if n <= 6:
        return "mid"
    return "high"


def arsenal_block(weakest_vector=None, thinking_level=None, perception_type=None) -> str:
    """Каталог под конкретного человека: его вектор, уровень и тип восприятия.

    Возвращает пустую строку, если профиля нет: без теста рекомендовать
    по векторам нечего, а вываливать весь каталог в обычный разговор —
    ровно то, чего делать нельзя.
    """
    if not weakest_vector and thinking_level is None and not perception_type:
        return ""

    parts = ["ЧТО У НАС ЕСТЬ (рекомендуй из этого, а не вообще):"]

    wv = (weakest_vector or "").strip().upper()[:2]
    if wv in VECTOR_BLOCKS:
        parts.append("Слабый вектор — сюда смотри в первую очередь:")
        parts.append(VECTOR_BLOCKS[wv])
        others = [v for v in ("СБ", "ТФ", "УБ", "ЧВ") if v != wv]
    else:
        others = ["СБ", "ТФ", "УБ", "ЧВ"]
    if others:
        parts.append("Остальные векторы — если разговор уйдёт туда:")
        for v in others:
            parts.append(VECTOR_BLOCKS[v])

    pt = (perception_type or "").upper()
    for key, hint in PERCEPTION_HINTS.items():
        if key in pt:
            parts.append(hint)
            break

    parts.append(LEVEL_HINTS[_level_key(thinking_level)])
    parts.append(BOOKS)
    parts.append(RULES)
    return "\n".join(parts) + "\n\n"
