MARK_RX = re.compile(r"\s*\[\[\s*SCN\s*:\s*([a-z_.\s]{2,48}?)\s*\]\][.,;:!]*\s*", re.I)
SCENARIO_MAX_TURNS = 6


def arm_on(user_id) -> bool:
    """Плечо «сценарии»: половина людей, независимо от чётности id."""
    try:
        uid = int(user_id or 0)
    except (TypeError, ValueError):
        return False
    return uid > 0 and (uid // 2) % 2 == 0


def strip_mark(text: str) -> str:
    if not text:
        return text
    return MARK_RX.sub(" ", text).strip()


def find_mark(text: str):
    m = MARK_RX.search(text or "")
    if not m:
        return None
    key = re.sub(r"\s+", "", m.group(1)).lower()
    return key or None


