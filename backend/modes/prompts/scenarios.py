VOICE_NOTE = ("Голосовой режим: метку [[SCN:…]] НЕ ставить — всё сказанное озвучивается. Остальное так же.\n")


def menu_prompt(voice: bool = False) -> str:
    """Первые реплики: правила и короткое меню сценариев — модель выбирает."""
    body = "\n".join(_menu_line(k, v) for k, v in SCENARIOS.items())
    return _rules() + (VOICE_NOTE if voice else "") + "\nСценарии (ключ — название — как узнать — что спросить):\n" + body + "\n"


def card_prompt(key: str, human_turns: int, voice: bool = False) -> str:
    """После выбора: только карточка выбранного сценария и напоминание, где мы."""
    s = SCENARIOS.get((key or "").lower())
    if not s:
        return ""
    where = {1: "первый", 2: "второй", 3: "третий", 4: "четвёртый", 5: "пятый"}.get(human_turns, "шестой")
    return (
        "=== СЦЕНАРИЙ ПО ПРОБЛЕМЕ (выбран) ===\n"
        f"Сценарий этого разговора выбран: {key}. Сейчас {where} ответ по сценарию (считая от реплики, где "
        "он выбран). Порядок: второй ответ — ответ на вопрос и первый ход; третий — одно действие на "
        "сегодня по ветке, коротко, без «шаг 1, шаг 2»; четвёртый-пятый — одним предложением, что "
        "разберёте дальше, чтобы человек видел путь. Список не зачитывать, сценарий не называть. Если "
        "человек ушёл в другое — идти за ним. Кризисный блок, правила про врача и про приглашение второго "
        "человека важнее сценария; номера телефонов не добавлять. Метку второй раз не ставить, кроме случая, "
        "когда тема сменилась на другой сценарий из списка — тогда [[SCN:новый_ключ]] один раз.\n"
        + (VOICE_NOTE if voice else "") + "\n" + _card(key, s) + "\n"
    )


def scenario_block(human_turns: int, picked: str = None, voice: bool = False) -> str:
    """Что подмешать в системный промпт на этом ходу.

    Первые две реплики без выбранного сценария — меню (в голосе, где метки
    нет и выбор не запоминается, меню держится до шестой реплики). После
    выбора — карточка выбранного до шестой реплики. Дальше — ничего:
    разговор обычный, с правилами «куда вести» справляется каталог."""
    try:
        n = int(human_turns or 1)
    except (TypeError, ValueError):
        n = 1
    picked = (picked or "").lower()
    if picked in SCENARIOS and n <= SCENARIO_MAX_TURNS:
        return card_prompt(picked, n, voice)
    if not picked and n <= (SCENARIO_MAX_TURNS if voice else 2):
        return menu_prompt(voice)
    return ""


def scenario_prompt() -> str:
    """Полный текст: правила и все карточки. Для чтения и проверки, в
    промпт целиком не кладётся (см. scenario_block)."""
    return _rules() + "\n" + "\n\n".join(_card(k, v) for k, v in SCENARIOS.items()) + "\n"


def picked_text(key: str) -> str:
    s = SCENARIOS.get((key or "").lower())
    return s["title"] if s else ""
