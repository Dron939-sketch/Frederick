def _card(key: str, s: dict) -> str:
    lines = [f"### {key} — {s['title']}",
             f"Узнаётся: {s['recognize']}.",
             "Спросить (по одному вопросу за ход, не оба сразу):"]
    lines += [f"  - {q}" for q in s["ask"]]
    lines.append("К третьему ответу дать (одно, по ветке, не всё подряд):")
    lines += [f"  - {g}" for g in s["give"]]
    lines.append(f"Не делать: {s['avoid']}.")
    lines.append(f"Куда вести после шестой реплики: {s['route']}.")
    lines.append(f"Когда текста мало: {s['specialist']}.")
    return "\n".join(lines)


def _menu_line(key: str, s: dict) -> str:
    asks = " / ".join(s["ask"])
    return f"- {key} — {s['title']}. Узнаётся: {s['recognize']}. Спросить: {asks}"


